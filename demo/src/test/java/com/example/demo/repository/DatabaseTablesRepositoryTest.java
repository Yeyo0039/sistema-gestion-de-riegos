package com.example.demo.repository;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Set;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.web.servlet.MockMvc;

import com.example.demo.repository.DatabaseTablesRepository;

@SpringBootTest(properties = {
        "spring.datasource.url=jdbc:h2:mem:database-tables;MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1",
        "spring.datasource.username=sa",
        "spring.datasource.password=",
        "spring.datasource.driver-class-name=org.h2.Driver"
})
@AutoConfigureMockMvc
class DatabaseTablesRepositoryTest {

    @Autowired
    private JdbcTemplate jdbc;

    @Autowired
    private DatabaseTablesRepository repository;

    @Autowired
    private MockMvc mockMvc;

    @BeforeEach
    void createTables() {
        jdbc.execute("DROP TABLE IF EXISTS etapa");
        jdbc.execute("DROP TABLE IF EXISTS especie");
        jdbc.execute("DROP TABLE IF EXISTS temperatura");
        jdbc.execute("DROP TABLE IF EXISTS tipo_sustrato");
        jdbc.execute("DROP TABLE IF EXISTS tipo");
        jdbc.execute("""
                CREATE TABLE tipo (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    nombre VARCHAR(100) NOT NULL UNIQUE,
                    descripcion VARCHAR(255)
                )
                """);
        jdbc.execute("""
                CREATE TABLE tipo_sustrato (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    nombre VARCHAR(100) NOT NULL UNIQUE,
                    descripcion VARCHAR(255)
                )
                """);
        jdbc.execute("""
                CREATE TABLE especie (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    nombre VARCHAR(100) NOT NULL,
                    tipo_id INTEGER NOT NULL,
                    descripcion VARCHAR(255)
                )
                """);
        jdbc.execute("""
                CREATE TABLE temperatura (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    optima_minima NUMERIC(5, 2) NOT NULL,
                    optima_maxima NUMERIC(5, 2) NOT NULL,
                    maximo_permitido NUMERIC(5, 2) NOT NULL,
                    minimo_permitido NUMERIC(5, 2) NOT NULL
                )
                """);
        jdbc.execute("""
                CREATE TABLE etapa (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    especie_id INTEGER NOT NULL,
                    tipo_sustrato_id INTEGER,
                    fase VARCHAR(100) NOT NULL,
                    intervalo INTEGER,
                    volumen INTEGER
                )
                """);
        jdbc.update("INSERT INTO tipo (nombre, descripcion) VALUES (?, ?)",
                "Hortaliza", "Plantas cultivadas para consumo alimenticio");
        jdbc.update("INSERT INTO tipo_sustrato (nombre) VALUES (?)", "Franco");
        jdbc.update("INSERT INTO especie (nombre, tipo_id, descripcion) VALUES (?, ?, ?)",
                "Tomate", 1, "Planta de huerto");
        jdbc.update("""
                INSERT INTO temperatura
                    (optima_minima, optima_maxima, maximo_permitido, minimo_permitido)
                VALUES (?, ?, ?, ?)
                """, 18, 25, 35, 5);
        jdbc.update("""
                INSERT INTO etapa (especie_id, tipo_sustrato_id, fase, intervalo, volumen)
                VALUES (?, ?, ?, ?, ?)
                """, 1, 1, "Vegetativa", 3, 500);
    }

    @Test
    void returnsEveryRealTableWithItsDatabaseColumnNames() {
        Map<String, List<Map<String, Object>>> tables = repository.findAllTables();

        assertEquals(List.of("tipo", "tipo_sustrato", "especie", "temperatura", "etapa"),
                new ArrayList<>(tables.keySet()));
        assertEquals(Set.of("id", "nombre", "descripcion"), tables.get("tipo").get(0).keySet());
        assertEquals("Hortaliza", tables.get("tipo").get(0).get("nombre"));
        assertEquals(Set.of("id", "nombre", "tipo_id", "descripcion"),
                tables.get("especie").get(0).keySet());
        assertEquals(Set.of("id", "optima_minima", "optima_maxima", "maximo_permitido", "minimo_permitido"),
                tables.get("temperatura").get(0).keySet());
        assertEquals(Set.of("id", "especie_id", "tipo_sustrato_id", "fase", "intervalo", "volumen"),
                tables.get("etapa").get(0).keySet());
    }

    @Test
    void rejectsTableNamesOutsideTheRealSchema() {
        assertThrows(IllegalArgumentException.class, () -> repository.findTable("users"));
    }

    @Test
    void serializesAllRealTablesAsJson() throws Exception {
        mockMvc.perform(get("/api/tablas"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.tipo[0].nombre").value("Hortaliza"))
                .andExpect(jsonPath("$.especie[0].tipo_id").value(1))
                .andExpect(jsonPath("$.temperatura[0].optima_minima").value(18))
                .andExpect(jsonPath("$.etapa[0].tipo_sustrato_id").value(1));
    }

    @Test
    void healthEndpointReportsTheConnectedDatabase() throws Exception {
        mockMvc.perform(get("/api/health"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.status").value("UP"))
                .andExpect(jsonPath("$.database").isNotEmpty());
    }
}
